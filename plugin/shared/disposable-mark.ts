/**
 * Marking a working directory as disposable where it is written, so a
 * collector can tell it from content that may be the only copy of something.
 *
 * The mark is the Cache Directory Tagging convention: a `CACHEDIR.TAG` file
 * whose content starts with its fixed signature. Tools outside Jig write the
 * same file in their caches, so one rule covers Jig's working directories and
 * theirs. `jig gc` sets aside an ignored directory carrying the tag, and
 * `SCRATCH_DIR` is the part of `.context/` Jig's procedures write throwaway
 * files to.
 */
import { lstatSync, mkdirSync, openSync, closeSync, writeSync } from "node:fs";
import { join } from "node:path";
import { attempt, type Outcome } from "./outcome.ts";

/** The tag file's name. */
export const CACHEDIR_TAG = "CACHEDIR.TAG";
/** The signature a tag file's content starts with. */
export const CACHEDIR_TAG_SIGNATURE =
  "Signature: 8a477f597d28d172789f06886806bc55";
/**
 * The line that opens a drive handoff's machine block
 * (`.context/pr-drive-<PR>.md`): the mark of a handoff the drive wrote, which
 * `jig gc` sets aside like a tagged directory.
 */
export const HANDOFF_MACHINE_BLOCK =
  "<!-- machine block: regenerated by drive-state.ts handoff; edits here are lost -->";
/** The marked part of `.context/`, relative to the worktree root. */
export const SCRATCH_DIR = ".context/scratch";

const TAG_CONTENT = `${CACHEDIR_TAG_SIGNATURE}
# This file marks a directory of Jig's working files that nothing needs once
# the work it belongs to is finished. For information about cache directory
# tags, see https://bford.info/cachedir/
`;

/**
 * Create `directory` when missing and tag it, leaving an existing tag alone.
 * A failure is a value: the caller's own write still goes ahead, and the
 * untagged directory only keeps a collector from setting it aside.
 */
export function markDisposable(
  directory: string,
): Outcome<undefined, "unmarked"> {
  return attempt("unmarked", `tagging ${directory}`, () => {
    mkdirSync(directory, { recursive: true });
    const tag = join(directory, CACHEDIR_TAG);
    try {
      lstatSync(tag);
      return undefined;
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
    let fd: number;
    try {
      fd = openSync(tag, "wx", 0o644);
    } catch (error) {
      // Another writer tagged it first.
      if ((error as NodeJS.ErrnoException).code === "EEXIST") return undefined;
      throw error;
    }
    try {
      writeSync(fd, TAG_CONTENT);
    } finally {
      closeSync(fd);
    }
    return undefined;
  });
}
