/**
 * A starter configuration from detected facts: each value the repository
 * already implies, nested under its section, with the evidence it came from
 * as comments above it.
 *
 * A repository without `.config/jig.yaml` gets a whole file; one with a file
 * gets only the fields it does not set yet. A value equal to the field's
 * default is left out, since writing it changes nothing, and so is a field
 * the schema does not know. An addition to a section the file already has
 * says so: pasted as a second section, it would be a duplicate key, which
 * every skill refuses. A field the file sets to null is offered as a
 * replacement of that line, for the same reason.
 */
import { isMapping, valueAt } from "../config-layers.ts";
import type { Fact } from "./fact.ts";

/** What the draft reads of the configuration schema: each field's path and default. */
interface DraftSchema {
  fields: { path: string; default?: unknown }[];
}

type DraftField = DraftSchema["fields"][number];

/** One field of the draft: its value and every fact behind it. */
interface Entry {
  field: DraftField;
  value: unknown;
  evidence: string[];
  /** The file already has this key, set to null: the line replaces it. */
  replaces: boolean;
}

const STARTER_HEADER = [
  "# Jig configuration for this repository: the values the Jig skills read.",
  "# Every field, its default and the skills that read it:",
  "# plugin/CONFIGURATION.md in the jig plugin.",
  "# Generated by /jig:audit config-fit; review before committing.",
];
const ADDITIONS_HEADER = "# Add to .config/jig.yaml:";
const MERGE_NOTE = "   # the file has this section: add the fields under it";
const REPLACE_NOTE = "   # the file sets this to null: replace that line";

/** Text YAML reads back as the same string without quotes. */
const PLAIN = /^[A-Za-z_][A-Za-z0-9_./-]*$/;
/** Words YAML may read as something other than text. */
const RESERVED = /^(true|false|null|yes|no|on|off|y|n)$/i;

function scalar(value: unknown): string {
  if (typeof value === "string")
    return PLAIN.test(value) && !RESERVED.test(value)
      ? value
      : JSON.stringify(value);
  return JSON.stringify(value) ?? "null";
}

/** A value in YAML's flow form: lists and maps on one line. */
function flow(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(flow).join(", ")}]`;
  if (isMapping(value))
    return `{ ${Object.entries(value)
      .map(([k, v]) => `${scalar(k)}: ${flow(v)}`)
      .join(", ")} }`;
  return scalar(value);
}

const same = (a: unknown, b: unknown) =>
  JSON.stringify(a) === JSON.stringify(b);

/** A list without its repeated values, in first-seen order; any other value as it is. */
function distinct(value: unknown): unknown {
  if (!Array.isArray(value)) return value;
  const kept: unknown[] = [];
  for (const v of value) if (!kept.some((e) => same(e, v))) kept.push(v);
  return kept;
}

/** Add one fact to its field's entry: a list's values add up, distinct. */
function merge(entry: Entry, fact: Fact): void {
  entry.evidence.push(...fact.evidence);
  if (Array.isArray(entry.value) && Array.isArray(fact.value))
    entry.value = distinct([...entry.value, ...fact.value]);
}

/**
 * The fields the draft writes, in the order first found: known to the
 * schema, not set by the repository's file (an empty value, null, sets
 * nothing), and not equal to the default.
 */
function entries(
  facts: Fact[],
  schema: DraftSchema,
  existing: Record<string, unknown>,
): Entry[] {
  const byPath = new Map(schema.fields.map((f) => [f.path, f]));
  const found = new Map<string, Entry>();
  for (const fact of facts) {
    const field = byPath.get(fact.field);
    const current = valueAt(existing, fact.field);
    if (field === undefined || current != null) continue;
    const entry = found.get(fact.field);
    if (entry) merge(entry, fact);
    else
      found.set(fact.field, {
        field,
        value: distinct(fact.value),
        evidence: [...fact.evidence],
        replaces: current === null,
      });
  }
  return [...found.values()].filter(
    (e) => e.field.default === undefined || !same(e.value, e.field.default),
  );
}

/** A section or a field, keyed by the next part of its path. */
type Tree = Map<string, Tree | Entry>;

function tree(fields: Entry[]): Tree {
  const root: Tree = new Map();
  for (const entry of fields) {
    const parts = entry.field.path.split(".");
    const name = parts.pop() ?? "";
    let node = root;
    for (const part of parts) {
      const next = node.get(part);
      const child = next instanceof Map ? next : new Map();
      node.set(part, child);
      node = child;
    }
    node.set(name, entry);
  }
  return root;
}

/** The YAML lines of a tree, nested two spaces per level. */
function lines(node: Tree, indent = ""): string[] {
  return [...node].flatMap(([key, child]) =>
    child instanceof Map
      ? [`${indent}${key}:`, ...lines(child, `${indent}  `)]
      : [
          ...child.evidence.map(
            (e) => `${indent}# ${e.replace(/\s*\n\s*/g, " ")}`,
          ),
          `${indent}${key}: ${flow(child.value)}${child.replaces ? REPLACE_NOTE : ""}`,
        ],
  );
}

/**
 * The starter configuration for `facts`, or undefined when there is nothing
 * to write. `existing` is the repository's file, or null when it has none.
 */
export function draftConfig(
  facts: Fact[],
  schema: DraftSchema,
  existing: Record<string, unknown> | null,
): string | undefined {
  const fields = entries(facts, schema, existing ?? {});
  if (fields.length === 0) return undefined;
  const body = lines(tree(fields));
  if (existing === null)
    return `${[...STARTER_HEADER, "", ...body].join("\n")}\n`;
  const marked = body.map((line) => {
    const section = /^([a-z_]+):$/.exec(line)?.[1];
    return section !== undefined && section in existing
      ? `${line}${MERGE_NOTE}`
      : line;
  });
  return `${[ADDITIONS_HEADER, ...marked].join("\n")}\n`;
}
