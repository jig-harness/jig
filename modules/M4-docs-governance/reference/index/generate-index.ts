#!/usr/bin/env bun
// Derive navigation from the docs tree; --check compares without committing it.
import {
  existsSync,
  readFileSync,
  writeFileSync,
  renameSync,
  unlinkSync,
} from "node:fs";
import { basename, join, relative, sep } from "node:path";
import { cli, frontmatterValue, markdownFiles, readDocument } from "../docs";
export function generateIndex(directory: string): string {
  const rows = markdownFiles(directory)
    .filter((file) => basename(file) !== "INDEX.md")
    .map((file) => {
      const relativePath = relative(directory, file).split(sep).join("/");
      const category = relativePath.includes("/")
        ? (relativePath.split("/")[0] ?? "")
        : "(root)";
      const text = readDocument(file);
      const title =
        frontmatterValue(text, "title") ||
        basename(file, ".md")
          .replace(/[-_]/g, " ")
          .split(/\s+/)
          .filter(Boolean)
          .map((word) => word[0]?.toUpperCase() + word.slice(1))
          .join(" ");
      return [
        category,
        relativePath,
        title,
        frontmatterValue(text, "description"),
      ];
    })
    .sort((a, b) =>
      Buffer.compare(Buffer.from(a.join("\t")), Buffer.from(b.join("\t"))),
    );
  let result =
    "<!-- AUTO-GENERATED by generate-index.ts — do not edit by hand. -->\n\n# Documentation index\n\n";
  for (const category of new Set(rows.map((row) => row[0]))) {
    result += `## ${category}\n\n| Doc | Title | Description |\n|-----|-------|-------------|\n`;
    for (const row of rows.filter((row) => row[0] === category))
      result += `| [${row[1]}](${row[1]}) | ${row[2]} | ${row[3]} |\n`;
    result += "\n";
  }
  return result;
}
export function runIndex(
  args = process.argv.slice(2),
  env = process.env,
): number {
  const directory = env.DOCS_DIR || "docs";
  const output = env.OUT || join(directory, "INDEX.md");
  if (!existsSync(directory)) throw new Error(`no such dir: ${directory}`);
  const generated = generateIndex(directory);
  if (args[0] === "--check") {
    if (!existsSync(output) || readFileSync(output, "utf8") !== generated) {
      console.log(
        `ERROR: ${output} is stale — regenerate with bun generate-index.ts`,
      );
      return 1;
    }
    console.log(`OK — ${output} is fresh`);
  } else {
    const temporary = `${output}.${process.pid}.tmp`;
    try {
      writeFileSync(temporary, generated);
      renameSync(temporary, output);
    } finally {
      if (existsSync(temporary)) {
        unlinkSync(temporary);
      }
    }
    console.log(`Wrote ${output}`);
  }
  return 0;
}
if (import.meta.main) cli(() => runIndex());
