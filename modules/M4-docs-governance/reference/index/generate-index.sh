#!/usr/bin/env bash
# Docs index generator + freshness check.
#
# Walks the docs tree, reads each doc's frontmatter title/description, and
# emits a grouped, sorted INDEX.md. Navigation is generated, never
# hand-curated (see ../../templates/WIKI-SCHEMA.md). This is M2's freshness
# triad applied to navigation — the `--check` mode is the drift gate.
#
# Portable: bash + awk + coreutils. No language runtime.
#
# Usage:
#   generate-index.sh                 # write $DOCS_DIR/INDEX.md
#   generate-index.sh --check         # regenerate to a temp file, diff against
#                                     # the committed INDEX, exit 1 if stale
#   DOCS_DIR=docs generate-index.sh
set -u
DOCS_DIR="${DOCS_DIR:-docs}"
OUT="${OUT:-$DOCS_DIR/INDEX.md}"
MODE="${1:-write}"

[ -d "$DOCS_DIR" ] || { echo "ERROR: no such dir: $DOCS_DIR" >&2; exit 2; }

fm_value() { # <file> <key> from leading frontmatter
  awk -v k="$2" '
    NR==1 && $0 !~ /^---[[:space:]]*$/ { exit }
    /^---[[:space:]]*$/ { d++; if (d==2) exit; next }
    d==1 && $0 ~ "^"k":[[:space:]]" {
      v=$0; sub("^"k":[[:space:]]*","",v);
      sub(/^["\047]/,"",v); sub(/["\047][[:space:]]*$/,"",v); print v; exit }
  ' "$1"
}

humanize() { # filename -> Title Case fallback
  basename "$1" .md | sed 's/[-_]/ /g' | awk '{for(i=1;i<=NF;i++)$i=toupper(substr($i,1,1))substr($i,2)}1'
}

generate() {
  echo "<!-- AUTO-GENERATED by generate-index.sh — do not edit by hand. -->"
  echo ""
  echo "# Documentation index"
  echo ""
  # Collect "category<TAB>relpath<TAB>title<TAB>description", sorted.
  local rows
  rows=$(
    find "$DOCS_DIR" -name '*.md' ! -name 'INDEX.md' 2>/dev/null | LC_ALL=C sort | while read -r f; do
      rel="${f#"$DOCS_DIR"/}"
      case "$rel" in */*) cat="${rel%%/*}";; *) cat="(root)";; esac
      title=$(fm_value "$f" title); [ -n "$title" ] || title=$(humanize "$f")
      desc=$(fm_value "$f" description)
      printf '%s\t%s\t%s\t%s\n' "$cat" "$rel" "$title" "$desc"
    done | LC_ALL=C sort
  )
  # Emit one section per category.
  printf '%s\n' "$rows" | awk -F'\t' 'NF>=3 {print $1}' | uniq | while read -r cat; do
    [ -n "$cat" ] || continue
    echo "## $cat"
    echo ""
    echo "| Doc | Title | Description |"
    echo "|-----|-------|-------------|"
    printf '%s\n' "$rows" | awk -F'\t' -v c="$cat" '$1==c {printf "| [%s](%s) | %s | %s |\n", $2, $2, $3, $4}'
    echo ""
  done
}

if [ "$MODE" = "--check" ]; then
  tmp=$(mktemp)
  trap 'rm -f "$tmp"' EXIT
  generate > "$tmp"
  if [ ! -f "$OUT" ] || ! diff -q "$OUT" "$tmp" >/dev/null; then
    echo "ERROR: $OUT is stale — regenerate with generate-index.sh"
    [ -f "$OUT" ] && diff "$OUT" "$tmp" | sed 's/^/  /' | head -n 40
    exit 1
  fi
  echo "OK — $OUT is fresh"
else
  generate > "$OUT"
  echo "Wrote $OUT"
fi
