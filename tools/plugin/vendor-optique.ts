#!/usr/bin/env bun
/**
 * Vendors Optique, the parser library the `jig` command line is written
 * with, into the plugin. The plugin runs from a copy with no `node_modules`
 * and Optique ships no single-file build, so this bundles the parts the
 * command line imports (optique-entry.ts) from the pinned package, with
 * Bun's bundler and no minification, and writes beside the plugin's other
 * vendored code:
 *
 *   plugin/shared/vendor/optique.mjs      the bundle
 *   plugin/shared/vendor/optique.d.mts    its declarations: the package's own
 *                                         types, which the type check reads
 *                                         from the repository's node_modules
 *   plugin/shared/vendor/optique.LICENSE  the package's licence
 *
 * Usage:
 *   bun tools/plugin/vendor-optique.ts           write the three files
 *   bun tools/plugin/vendor-optique.ts --check   exit 1 naming each file that
 *                                                differs from a fresh build
 *
 * The bundle is what the pinned Bun writes for the pinned package, so an
 * update of either is followed by a run of this script.
 */
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { cli } from "../../lib/cli.ts";

const ROOT = resolve(import.meta.dir, "../..");
const ENTRY = "tools/plugin/optique-entry.ts";
const PACKAGE = "node_modules/@optique/core";
export const VENDOR_DIR = "plugin/shared/vendor";
const COMMAND = "bun tools/plugin/vendor-optique.ts";

/** A bundle that could not be built; the message says why. */
class VendorError extends Error {
  override name = "VendorError";
}

function packageVersion(): string {
  const manifest: unknown = JSON.parse(
    readFileSync(join(ROOT, PACKAGE, "package.json"), "utf8"),
  );
  const version =
    typeof manifest === "object" && manifest !== null && "version" in manifest
      ? manifest.version
      : undefined;
  if (typeof version !== "string")
    throw new VendorError(`${PACKAGE}/package.json names no version`);
  return version;
}

/**
 * Bun's bundle of the entry. The bundler names each module's source path
 * relative to its working directory in a comment, so it runs from the
 * repository root wherever this is called from.
 */
function bundle(banner: string): string {
  const scratch = mkdtempSync(join(tmpdir(), "vendor-optique-"));
  try {
    const out = join(scratch, "optique.mjs");
    const build = Bun.spawnSync(
      [
        process.execPath,
        "build",
        ENTRY,
        "--target=bun",
        "--format=esm",
        `--banner=${banner}`,
        `--outfile=${out}`,
      ],
      { cwd: ROOT, stdout: "pipe", stderr: "pipe" },
    );
    if (build.exitCode !== 0)
      throw new VendorError(
        `bun build ${ENTRY} failed (exit ${build.exitCode}):\n${build.stderr.toString()}`,
      );
    return readFileSync(out, "utf8");
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

/** The entry's export statements, which name the package's own types. */
function declarations(version: string): string {
  const entry = readFileSync(join(ROOT, ENTRY), "utf8");
  const exports = entry.slice(entry.search(/^export /m));
  return `// Types for the vendored Optique ${version} bundle (optique.mjs): the pinned
// package's own, read from node_modules when the repository is type-checked.
// Generated by \`${COMMAND}\`; do not edit.
${exports}`;
}

/** Each vendored file's name and the content a fresh build gives it. */
export function vendoredOptique(): Record<string, string> {
  const version = packageVersion();
  return {
    "optique.mjs": bundle(
      `// Optique (@optique/core) ${version}, MIT License (optique.LICENSE), bundled by \`${COMMAND}\`; do not edit.`,
    ),
    "optique.d.mts": declarations(version),
    "optique.LICENSE": readFileSync(join(ROOT, PACKAGE, "LICENSE"), "utf8"),
  };
}

function main(args: string[]): number {
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    console.error(`Usage: ${COMMAND} [--check]`);
    return 2;
  }
  const files = vendoredOptique();
  if (args[0] !== "--check") {
    for (const [name, content] of Object.entries(files))
      writeFileSync(join(ROOT, VENDOR_DIR, name), content);
    return 0;
  }
  const stale = Object.entries(files)
    .map(([name, content]) => ({ path: `${VENDOR_DIR}/${name}`, content }))
    .filter(
      ({ path, content }) =>
        !existsSync(join(ROOT, path)) ||
        readFileSync(join(ROOT, path), "utf8") !== content,
    )
    .map(({ path }) => path);
  for (const path of stale)
    console.error(`${path} differs from a fresh build; run ${COMMAND}`);
  return stale.length === 0 ? 0 : 1;
}

if (import.meta.main) cli(() => main(process.argv.slice(2)));
