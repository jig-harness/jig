import { windowsUnsafeName } from "./integrity.ts";

export type Overlay = Record<string, unknown> & {
  skills: string[];
  harness?: {
    claude_frontmatter?: Record<string, Record<string, string>>;
    codex_frontmatter?: Record<string, Record<string, string>>;
  };
};
export const skillName = (name: string): boolean =>
  /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name) && !windowsUnsafeName(name);
const isRecord = (value: unknown): value is Record<string, unknown> =>
  Boolean(value) && typeof value === "object" && !Array.isArray(value);
export function validateOverlay(value: unknown): asserts value is Overlay {
  if (
    !value ||
    typeof value !== "object" ||
    !Array.isArray((value as Overlay).skills)
  )
    throw new Error("overlay needs a skills array");
  const skills = (value as Overlay).skills;
  if (
    skills.some((name) => typeof name !== "string" || !skillName(name)) ||
    new Set(skills).size !== skills.length
  )
    throw new Error("overlay skills must be unique plain names");
  const harness = (value as Overlay).harness as unknown;
  if (harness === undefined) return;
  if (!isRecord(harness)) throw new Error("overlay harness must be a mapping");
  for (const surface of ["claude_frontmatter", "codex_frontmatter"]) {
    const bySkill = harness[surface];
    if (bySkill === undefined) continue;
    if (!isRecord(bySkill))
      throw new Error(`overlay harness.${surface} must be a mapping`);
    for (const [name, fields] of Object.entries(bySkill))
      if (!isRecord(fields))
        throw new Error(`overlay harness.${surface}.${name} must be a mapping`);
  }
}
export function render(
  source: string,
  overlay: Overlay,
  skill: string,
  surface: "claude" | "codex",
): string {
  const match = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)([\s\S]*)$/.exec(source);
  if (!match) throw new Error(`${skill} needs YAML frontmatter`);
  const header = match[1] ?? "";
  // Supported boundary: every column-zero line is a comment or a plain or
  // quoted key; indented lines continue the previous value. Anything else (explicit
  // `?` keys, tags, anchors, flow mappings) could hide a canonical key, so refuse it.
  const keys = new Set<string>();
  for (const line of header.split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    // Indentation continues a value only after a key; an indented root mapping is unsupported.
    if (/^\s/.test(line) && keys.size) continue;
    const m = /^(?:"([^"\\]+)"|'([^']+)'|([\w-]+))[ \t]*:(?:[ \t]|$)/.exec(
      line,
    );
    const key = m?.[1] ?? m?.[2] ?? m?.[3];
    if (!key)
      throw new Error(
        `${skill} frontmatter has an unsupported key form: ${line}`,
      );
    keys.add(key);
  }
  const injected = overlay.harness?.[`${surface}_frontmatter`]?.[skill] ?? {};
  const additions = Object.entries(injected)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => {
      if (
        !/^[\w-]+$/.test(key) ||
        keys.has(key) ||
        typeof value !== "string" ||
        [...value].some(
          (char) =>
            char.charCodeAt(0) < 32 ||
            [127, 133, 8232, 8233].includes(char.charCodeAt(0)),
        )
      )
        throw new Error(`invalid or shadowed frontmatter: ${skill}.${key}`);
      return `${key}: ${JSON.stringify(value)}`;
    });
  const body = (match[2] ?? "").replace(
    /\{\{\s*([\w]+(?:\.[\w]+)*)\s*\}\}/g,
    (_whole, path: string) => {
      let value: unknown = overlay;
      for (const key of path.split(".")) {
        if (!value || typeof value !== "object" || !Object.hasOwn(value, key))
          throw new Error(`missing overlay value: ${path}`);
        value = (value as Record<string, unknown>)[key];
      }
      if (typeof value === "string") return value;
      if (typeof value === "number" || typeof value === "boolean")
        return String(value);
      if (
        Array.isArray(value) &&
        value.every((item) => typeof item === "string")
      )
        return value.join(", ");
      throw new Error(`overlay value is not printable: ${path}`);
    },
  );
  return `---\n${[header, ...additions].join("\n")}\n---\n\n<!-- Generated by Groundwork; edit the source or consumer overlay. -->\n${body}`;
}
